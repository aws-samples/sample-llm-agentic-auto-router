// Regenerates src/catalog.data.ts from every data/catalog.<region>.json, and src/meta.data.ts from data/models.json
// and data/family-defaults.json (the runtime images copy src/ only, so data the Lambdas and the router read at run
// time is embedded as modules).
// Run: node packages/pricing/scripts/gen-catalog.ts   (Node 24 strips the types natively)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const files = readdirSync(`${root}data`).filter((f) => /^catalog\.[a-z0-9-]+\.json$/.test(f)).sort()
const catalogs: Record<string, unknown> = {}
for (const f of files) {
  const json = JSON.parse(readFileSync(`${root}data/${f}`, 'utf8')) as { region: string }
  if (`catalog.${json.region}.json` !== f) throw new Error(`${f}: region field is '${json.region}'`)
  catalogs[json.region] = json
}
const out = `// GENERATED by scripts/gen-catalog.ts from data/catalog.<region>.json. Do not edit by hand.
import type { PriceCatalog } from './types.ts'

export const CATALOGS: Readonly<Record<string, PriceCatalog>> = ${JSON.stringify(catalogs, null, 2)}
`
writeFileSync(`${root}src/catalog.data.ts`, out)
console.log(`wrote src/catalog.data.ts (${Object.keys(catalogs).join(', ')})`)

const withoutComment = (f: string): unknown => {
  const { $comment: _c, ...rest } = JSON.parse(readFileSync(`${root}data/${f}`, 'utf8')) as Record<string, unknown>
  return rest
}
const meta = `// GENERATED by scripts/gen-catalog.ts from data/models.json and data/family-defaults.json. Do not edit by hand.
import type { ModelsFile } from './build.ts'
import type { FamilyDefaults } from './templates.ts'

export const SHIPPED_MODELS: ModelsFile = ${JSON.stringify(withoutComment('models.json'), null, 2)}

export const FAMILY_DEFAULTS: FamilyDefaults = ${JSON.stringify(withoutComment('family-defaults.json'), null, 2)}
`
writeFileSync(`${root}src/meta.data.ts`, meta)
console.log('wrote src/meta.data.ts (models.json, family-defaults.json)')
